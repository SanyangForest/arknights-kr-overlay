# (받침 있을 때, 없을 때). 긴 것부터 찾는다.
PARTICLES = [
    ("으로", "로"), ("이에요", "예요"), ("이었", "였"), ("이야", "야"), ("이라", "라"),
    ("이랑", "랑"), ("이나", "나"), ("이다", "다"),
    ("은", "는"), ("이", "가"), ("을", "를"), ("과", "와"),
]
CLOSERS = ["</color>", "</>", ">", "」", "』", "》", "】", "]", ")", "'", "’", "\"", "”"]


def batchim(word):
    """마지막 글자의 받침: None(없음), 'ㄹ', 'other'."""
    c = word[-1]
    if not "가" <= c <= "힣":
        return None
    jong = (ord(c) - 0xAC00) % 28
    return None if jong == 0 else ("ㄹ" if jong == 8 else "other")


def particle_for(word, pair):
    with_b, without_b = pair
    b = batchim(word)
    if pair[0] == "으로":
        return "으로" if b == "other" else "로"
    return with_b if b else without_b


def replace_name(ko, old, new):
    out, i = [], 0
    while True:
        j = ko.find(old, i)
        if j < 0:
            out.append(ko[i:])
            return "".join(out)
        # 이미 정한 표기 안에 든 것(자모레스크 속 '자모레스')은 두 번 바꾸지 않는다
        o = next((o for o in range(len(new) - len(old) + 1)
                  if j - o >= i and new.startswith(old, o) and ko.startswith(new, j - o)), None)
        if o is not None:
            out.append(ko[i:j - o] + new)
            i = j - o + len(new)
            continue
        out.append(ko[i:j])
        out.append(new)
        k = j + len(old)
        # 이름을 감싼 닫는 기호(<채집기지>가, '원단'을) 뒤의 조사도 맞춘다
        while (close := next((c for c in CLOSERS if ko.startswith(c, k)), None)):
            out.append(close)
            k += len(close)
        for pair in PARTICLES:
            hit = next((p for p in pair if ko.startswith(p, k)), None)
            if hit:
                # '이' 뒤에 한글이 이어지면 조사가 아닌 다른 말일 수 있다 (예: '이번').
                nxt = ko[k + len(hit):k + len(hit) + 1]
                if hit == "이" and nxt and "가" <= nxt <= "힣":
                    break
                out.append(particle_for(new, pair))
                k += len(hit)
                break
        i = k


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    dry = "--dry" in sys.argv
    total = 0
    for tsv in sorted((ROOT / "extra").glob("claude_*.tsv")):
        lines = tsv.read_text(encoding="utf-8").split("\n")
        changed = 0
        for n, line in enumerate(lines[1:], 1):
            cols = line.split("\t")
            if len(cols) < 2:
                continue
            zh, ko = unesc(cols[0]), unesc(cols[1])
            new = ko
            for term, old, fixed in RULES:
                if term in zh and old in new:
                    new = replace_name(new, old, fixed)
            if new != ko:
                if dry and changed < 3:
                    print(f"  {ko[:60]!r}\n→ {new[:60]!r}")
                cols[1] = esc(new)
                lines[n] = "\t".join(cols)
                changed += 1
        if changed:
            print(f"{tsv.name}: {changed}줄")
            total += changed
            if not dry:
                tsv.write_text("\n".join(lines), encoding="utf-8")
    print(f"합계 {total}줄" + (" (미리보기)" if dry else ""))


if __name__ == "__main__":
    main()
